-- Global reference catalogs are readable by players and writable only by admins/server code.
DO $$
DECLARE table_name text; p record;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['goods','good_variants','resource_types','production_recipes']
  LOOP
    FOR p IN
      SELECT policyname FROM pg_policies
      WHERE schemaname='public' AND tablename=table_name AND cmd IN ('INSERT','UPDATE','DELETE','ALL')
    LOOP
      EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', p.policyname, table_name);
    END LOOP;
    EXECUTE format(
      'CREATE POLICY %I ON public.%I FOR ALL TO authenticated USING (public.has_role(auth.uid(), ''admin'')) WITH CHECK (public.has_role(auth.uid(), ''admin''))',
      left(table_name || '_admin_write', 63), table_name
    );
  END LOOP;
END
$$;

