-- Parent-scoped legacy and projection tables.
DROP POLICY IF EXISTS "Public access to legacy military map" ON public.legacy_military_map;
DROP POLICY IF EXISTS public_read_legacy_military_map ON public.legacy_military_map;
CREATE POLICY legacy_military_map_session_access
ON public.legacy_military_map FOR ALL TO authenticated
USING (EXISTS (
  SELECT 1 FROM public.military_stacks s
  WHERE s.id = legacy_military_map.stack_id
    AND app_private.is_session_member(s.session_id)
))
WITH CHECK (EXISTS (
  SELECT 1 FROM public.military_stacks s
  WHERE s.id = legacy_military_map.stack_id
    AND app_private.is_session_member(s.session_id)
));

