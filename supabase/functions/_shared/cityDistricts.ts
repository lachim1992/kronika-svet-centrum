/**
 * City district catalogue — two families that depend on each other.
 *
 * Residential districts house people: they raise housing capacity and, because those
 * households consume, they raise basket demand. They also provide the labour pool.
 * Production districts turn that labour into goods for one chosen demand basket.
 *
 * One residential district staffs PRODUCTION_PER_RESIDENTIAL production districts.
 * Unstaffed production districts stand idle and supply nothing.
 */

export const PRODUCTION_PER_RESIDENTIAL = 2;

export interface DistrictBlueprint {
  key: string;
  name: string;
  district_type: "residential" | "production";
  population_capacity?: number;
  /** Extra basket demand generated by the households (spread over the tiers). */
  demand_bonus?: number;
  /** Production districts: units delivered into the chosen basket each turn. */
  basket_output?: number;
  basket_quality?: number;
  build_cost_wealth: number;
  build_cost_wood?: number;
  build_cost_stone?: number;
  build_turns: number;
  grain_modifier?: number;
  wealth_modifier?: number;
  production_modifier?: number;
  stability_modifier?: number;
  peasant_attraction?: number;
  burgher_attraction?: number;
  /** Baskets this district may be set to produce; empty means all baskets. */
  baskets?: string[];
  description: string;
}

